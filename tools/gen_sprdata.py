# writes sprdata.js (SPR_UNITS / SPR_ALIAS / SPR_K / SPR_V) from game3d.js so other modes (td.js) share the sprite list
import re
s=open('game3d.js').read()
u=re.search(r"const SPR_UNITS=(\[[^\]]*\])",s).group(1)
a=re.search(r"const SPR_ALIAS=(\{.*?\});",s).group(1)
k=re.search(r"const SPR_K=(\{[^}]*\})",s).group(1)
v=re.search(r"SPR_V=(\d+)",s).group(1)
open('sprdata.js','w').write(f"// generated by tools/gen_sprdata.py from game3d.js — do not edit\nexport const SPR_UNITS={u};\nexport const SPR_ALIAS={a};\nexport const SPR_K={k};\nexport const SPR_V={v};\n")
print('ok',len(u))
